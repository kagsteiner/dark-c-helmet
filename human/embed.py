#!/usr/bin/env python3
"""Generate human/hnet_data.c embedding human-player networks (bin/human-train output) as
16-bit floats, one per rating band. The file name names the band and version:
net_h1300_v1.hnet -> band 1300, used by the profile "1300".

Usage: python3 human/embed.py net_h1300_v1.hnet [net_h1600_v1.hnet ...]
"""
import struct
import sys
from array import array
from pathlib import Path

out = Path(__file__).resolve().parent / "hnet_data.c"
lines = ["// Generated by human/embed.py. Do not edit.", "#include <stdint.h>", "",
         "typedef struct { const char* name; const uint16_t* data; unsigned count; } EmbeddedNet;", ""]
nets = []
for k, arg in enumerate(sys.argv[1:]):
    src = Path(arg)
    data = src.read_bytes()
    if data[:5] != b"HNET1":
        sys.exit(f"{src}: not a human-player network")
    floats = array("f")
    floats.frombytes(data[24:])
    halves = struct.unpack(f"<{len(floats)}H", struct.pack(f"<{len(floats)}e", *floats))
    name = src.stem.removeprefix("net_")
    nets.append((name, f"net{k}", len(halves)))
    lines.append(f"static const uint16_t net{k}[] = {{")
    for i in range(0, len(halves), 20):
        lines.append("    " + ",".join(str(h) for h in halves[i:i + 20]) + ",")
    lines.append("};")
    print(f"{name}: {len(halves)} weights, {2 * len(halves) // 1024} KB")
lines.append("const EmbeddedNet HNET_EMBEDDED[] = {")
lines += [f'    {{"{n}", {v}, {c}}},' for n, v, c in nets] or ["    {0, 0, 0},"]
lines.append("};")
lines.append(f"const int HNET_EMBEDDED_NETS = {len(nets)};")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
